/**
 * Rendering of literature-review outputs, shared by the UI and the
 * Markdown / DOCX / report exports so every surface shows the same data.
 *
 * Structured outputs are stored as JSON in one of these shapes:
 * - table:     { columns: ({ key, label } | string)[], rows: object[], note? }
 * - framework: { categories: [{ name, description, codes: [{ name, description, studies }] }], note? }
 * - sections:  { someSection: object[] | { metric: value }, ..., note? }
 */

export interface TableColumn {
	key: string;
	label: string;
}

export type RenderBlock =
	| { kind: 'table'; title?: string; columns: TableColumn[]; rows: Record<string, unknown>[] }
	| { kind: 'keyValue'; title?: string; entries: [string, string][] }
	| { kind: 'note'; text: string }
	| { kind: 'code'; text: string };

type Row = Record<string, unknown>;

/** "records_after_dedup" / "byYear" → "Records After Dedup" / "By Year". */
export function humanizeKey(key: string): string {
	return key
		.replace(/_/g, ' ')
		.replace(/([a-z0-9])([A-Z])/g, '$1 $2')
		.replace(/\s+/g, ' ')
		.trim()
		.replace(/\b\w/g, (c) => c.toUpperCase());
}

/** Display text for a cell. Only missing values become "—" (0 and false are kept). */
export function formatCell(value: unknown): string {
	if (value === null || value === undefined || value === '') return '—';
	if (Array.isArray(value)) return value.length ? value.map(formatCell).join('; ') : '—';
	if (typeof value === 'object') return JSON.stringify(value);
	return String(value);
}

/**
 * Resolves columns to row keys. Current outputs store `{ key, label }`;
 * outputs generated by older versions stored bare labels, which are matched
 * to row keys by name, then by position.
 */
export function normalizeColumns(columns: unknown[], rows: Row[]): TableColumn[] {
	const sampleKeys = rows.length > 0 ? Object.keys(rows[0]) : [];
	return columns.map((col, i) => {
		if (col && typeof col === 'object' && 'key' in col) {
			const c = col as { key: string; label?: string };
			return { key: String(c.key), label: String(c.label ?? humanizeKey(String(c.key))) };
		}
		const label = String(col);
		const compact = label.toLowerCase().replace(/[^a-z]/g, '');
		const key =
			sampleKeys.find((k) => k === label) ??
			sampleKeys.find((k) => k.toLowerCase() === compact) ??
			sampleKeys[i] ??
			label;
		return { key, label };
	});
}

function isPlainObject(value: unknown): value is Row {
	return !!value && typeof value === 'object' && !Array.isArray(value);
}

function isScalar(value: unknown): boolean {
	return value === null || ['string', 'number', 'boolean'].includes(typeof value);
}

function tableFromObjects(rows: Row[], title?: string): RenderBlock {
	const keys: string[] = [];
	for (const row of rows) for (const k of Object.keys(row)) if (!keys.includes(k)) keys.push(k);
	return {
		kind: 'table',
		title,
		columns: keys.map((key) => ({ key, label: humanizeKey(key) })),
		rows
	};
}

/** Converts a stored JSON output into displayable blocks. */
export function jsonOutputToBlocks(data: unknown): RenderBlock[] {
	if (!isPlainObject(data)) {
		return [{ kind: 'code', text: JSON.stringify(data, null, 2) }];
	}

	const blocks: RenderBlock[] = [];
	if (typeof data.note === 'string' && data.note) blocks.push({ kind: 'note', text: data.note });

	if (Array.isArray(data.columns) && Array.isArray(data.rows)) {
		const rows = data.rows.filter(isPlainObject);
		blocks.push({ kind: 'table', columns: normalizeColumns(data.columns, rows), rows });
		return blocks;
	}

	if (Array.isArray(data.categories)) {
		const rows: Row[] = [];
		for (const category of data.categories.filter(isPlainObject)) {
			const codes = Array.isArray(category.codes) ? category.codes.filter(isPlainObject) : [];
			if (codes.length === 0) {
				rows.push({
					category: category.name,
					code: '',
					description: category.description,
					studies: ''
				});
			}
			for (const code of codes) {
				rows.push({
					category: category.name,
					code: code.name,
					description: code.description,
					studies: code.studies ?? code.studyIndices
				});
			}
		}
		blocks.push({
			kind: 'table',
			columns: [
				{ key: 'category', label: 'Category' },
				{ key: 'code', label: 'Code' },
				{ key: 'description', label: 'Description' },
				{ key: 'studies', label: 'Studies' }
			],
			rows
		});
		return blocks;
	}

	const scalars: [string, string][] = [];
	for (const [key, value] of Object.entries(data)) {
		if (key === 'note') continue;
		if (Array.isArray(value)) {
			const rows = value.filter(isPlainObject);
			if (rows.length > 0) blocks.push(tableFromObjects(rows, humanizeKey(key)));
			else if (value.length > 0)
				blocks.push({
					kind: 'keyValue',
					title: humanizeKey(key),
					entries: value.map((v, i) => [String(i + 1), formatCell(v)])
				});
		} else if (isPlainObject(value)) {
			const entries = Object.entries(value).map(([k, v]): [string, string] => [
				humanizeKey(k),
				isScalar(v) ? formatCell(v) : JSON.stringify(v)
			]);
			blocks.push({ kind: 'keyValue', title: humanizeKey(key), entries });
		} else {
			scalars.push([humanizeKey(key), formatCell(value)]);
		}
	}
	if (scalars.length > 0) blocks.unshift({ kind: 'keyValue', entries: scalars });
	return blocks;
}

function escapeMarkdownCell(text: string): string {
	return text.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

export function blocksToMarkdown(blocks: RenderBlock[], headingLevel = 3): string {
	const heading = '#'.repeat(Math.min(headingLevel, 6));
	const parts: string[] = [];

	for (const block of blocks) {
		if (block.kind === 'note') {
			parts.push(`> ${block.text}`);
			continue;
		}
		if (block.kind === 'code') {
			parts.push('```json\n' + block.text + '\n```');
			continue;
		}
		const lines: string[] = [];
		if (block.title) lines.push(`${heading} ${block.title}`, '');
		if (block.kind === 'table') {
			lines.push('| ' + block.columns.map((c) => escapeMarkdownCell(c.label)).join(' | ') + ' |');
			lines.push('| ' + block.columns.map(() => '---').join(' | ') + ' |');
			for (const row of block.rows) {
				lines.push(
					'| ' +
						block.columns.map((c) => escapeMarkdownCell(formatCell(row[c.key]))).join(' | ') +
						' |'
				);
			}
		} else {
			lines.push('| Item | Value |', '| --- | --- |');
			for (const [k, v] of block.entries)
				lines.push(`| ${escapeMarkdownCell(k)} | ${escapeMarkdownCell(v)} |`);
		}
		parts.push(lines.join('\n'));
	}

	return parts.join('\n\n');
}

export interface StoredOutput {
	title: string;
	contentMarkdown?: string | null;
	contentJson?: string | null;
}

/** Markdown body of an output (without its title). Prefers the markdown rendering when present. */
export function outputBodyToMarkdown(output: StoredOutput, headingLevel = 3): string {
	if (output.contentMarkdown) return output.contentMarkdown;
	if (output.contentJson) {
		try {
			return blocksToMarkdown(jsonOutputToBlocks(JSON.parse(output.contentJson)), headingLevel);
		} catch {
			return '```\n' + output.contentJson + '\n```';
		}
	}
	return '_No content available._';
}
